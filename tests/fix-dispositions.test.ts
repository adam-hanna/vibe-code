function fixture(name: string): string {
  return readFileSync(fileURLToPath(new URL(`../../tests/fixtures/prompts/${name}`, import.meta.url)), 'utf8');
}

const PLAN = planFixture({ plan_md: PLAN_MD, out_of_scope: [...OUT_OF_SCOPE] });

const DISPOSITIONS_BLOCK =
  '\n## Dispositions\n\nReturn your final message as JSON in the response schema. `report` holds the whole ' +
  'report described above, with its five headings: it is what the next reviewer reads. `dispositions` has one ' +
  'entry for each finding id listed above (`finding-one`, `finding-two`): `disposition` is `fixed`, ' +
  '`rebutted`, `deferred` or `not-addressed`, and `reason` says why in a sentence or two. Use only those ids.\n';

// ---- the prompt ------------------------------------------------------------

/**
 * #506's splices, each of which must find its anchor in the golden, so the
 * comparisons below still prove nothing else in the prompt moved. Case 2 of
 * AGENTS.md both times: `fix breadth`'s remedy sentence called every finding's
 * suggested fix the reviewer's, which the planner reads too; and a review fix
 * turn's report bullet named three dispositions beside `## Dispositions` asking
 * for one of four.
 */
const REMEDY_506 = [
  "even when you reject the reviewer's proposed remedy.",
  "even when you reject a finding's proposed remedy.",
] as const;
const REPORT_BULLET_506 = [
  "- In your report, state each finding's disposition (fixed, rebutted, or deferred)\n",
  "- In your report, state each finding's disposition (the one you give it in `dispositions`, below)\n",
] as const;

/**
 * #483's splice: every writer turn is given `existing tests` immediately before
 * "Do not commit". Case 2 of AGENTS.md: the fix prompts said nothing about
 * editing a test to make a gate pass. These renderings pass no environment, so
 * the environment block adds nothing here (`writer-gates.test.ts` has the rest).
 */
const EXISTING_TESTS = promptBlocks().find((b) => b.name === 'existing tests')?.fallback ?? '<missing>';
const TESTS_483 = [
  'Do not commit - the orchestrator handles git.',
  `${EXISTING_TESTS}\n\nDo not commit - the orchestrator handles git.`,
] as const;

function spliced(golden: string, splices: readonly (readonly [string, string])[]): string {
  let out = golden;
  for (const [from, to] of splices) {
    assert.equal(out.split(from).length, 2, `the golden carries ${JSON.stringify(from)} exactly once`);
    out = out.replace(from, to);
  }
  return out;
}

test('without dispositions the fix prompt is the reviewed golden, which is develop\'s output byte for byte', () => {
  // `fix-round1.txt` was generated by `a689e46`'s own `fixPrompt` from these
  // arguments, so this is the verify-fix rendering pinned against develop,
  // with #506's one sentence of `fix breadth` spliced in, and #483's block.
  const golden = spliced(fixture('fix-round1.txt'), [REMEDY_506, TESTS_483]);
  assert.equal(fixPrompt(BLOCKING, 1, CRITERIA, PLAN), golden);
  assert.equal(fixPrompt(BLOCKING, 1, CRITERIA, PLAN, false), golden);
});

test('a review fix prompt is that golden followed by exactly the dispositions block, naming every id', () => {
  // Case 2 of AGENTS.md: the review fix turns' contract moved, by this and
  // nothing else - and, since #506, by the report bullet deferring to it.
  assert.equal(
    fixPrompt(BLOCKING, 1, CRITERIA, PLAN, true),
    spliced(fixture('fix-round1.txt'), [REMEDY_506, REPORT_BULLET_506, TESTS_483]) + DISPOSITIONS_BLOCK,
  );
});

test('a review fix prompt gives one disposition vocabulary, the four values `## Dispositions` asks for (#506)', () => {
  const prompt = fixPrompt(BLOCKING, 1, CRITERIA, PLAN, true);
  assert.ok(!prompt.includes('(fixed, rebutted, or deferred)'), 'no three-way list beside the four-way one');
  assert.ok(prompt.includes('`fixed`, `rebutted`, `deferred` or `not-addressed`'), 'the four values are named');
  // Still in the report, which is the only thing the next reviewer reads.
  const bullet = prompt.indexOf("- In your report, state each finding's disposition (the one you give it in `dispositions`, below)");
  const block = prompt.indexOf('\n## Dispositions\n');
  assert.ok(bullet !== -1, 'the report bullet is there');
  assert.ok(block !== -1, 'the block is there');
  assert.ok(bullet < block, 'the bullet points below, at the block');
  // The verify-fix turn has no block, so it keeps the values in prose.
  const verify = fixPrompt(BLOCKING, 1, CRITERIA, PLAN, false);
  assert.ok(verify.includes('(fixed, rebutted, or deferred)'));
  assert.ok(!verify.includes('`dispositions`'));
});

test("`fix breadth` calls a suggested fix a finding's proposed remedy, on every turn that reads it (#506)", () => {
  const turns = {
    implement: implementPrompt(PLAN_MD),
    'verify-fix': fixPrompt(BLOCKING, 1, CRITERIA, PLAN, false),
    fix: fixPrompt(BLOCKING, 1, CRITERIA, PLAN, true),
    revise: revisePlanPrompt({ planMd: PLAN_MD, outOfScope: OUT_OF_SCOPE, acceptanceCriteria: CRITERIA, findings: BLOCKING, round: 1 }),
  };
  for (const [turn, prompt] of Object.entries(turns)) {
    assert.ok(prompt.includes("even when you reject a finding's proposed remedy."), turn);
    assert.ok(!prompt.includes("the reviewer's proposed remedy"), turn);
  }
});

test('the implement prompt carries no dispositions request', () => {
  assert.equal(implementPrompt(PLAN_MD).includes('## Dispositions'), false);
});

// ---- the parse -------------------------------------------------------------

test('parseFixOutput reads the report and every disposition', () => {
  assert.deepEqual(
    parseFixOutput({ report: 'R', dispositions: [{ id: 'a', disposition: 'rebutted', reason: 'no' }] }),
    { report: 'R', dispositions: [{ id: 'a', disposition: 'rebutted', reason: 'no' }] },
  );
});

test('parseFixOutput throws on any malformed entry rather than dropping it', () => {
  for (const bad of [
    null,
    'text',
    { dispositions: [] },
    { report: 'R' },
    { report: 'R', dispositions: [{ id: 'a', disposition: 'maybe', reason: '' }] },
    { report: 'R', dispositions: [{ id: 'a', disposition: 'fixed' }] },
    { report: 'R', dispositions: [{ id: 'a', disposition: 'fixed', reason: 'ok' }, 7] },
  ]) {
    assert.throws(() => parseFixOutput(bad), ShapeError, JSON.stringify(bad));
  }
});

// ---- the join --------------------------------------------------------------

const STAMP: ReviewSeat = { round: 0, provider: 'codex', model: 'gpt-x' };
const CTX: { round: number; label: string; answers: number; reviewSeat: ReviewSeat | undefined } = {
  round: 1,
  label: 'fix-1',
  answers: 0,
  reviewSeat: STAMP,
};

test('one disposition per finding shown, in order: left out is not-addressed, invented is dropped, repeated keeps the first', () => {
  const findings: Finding[] = [{ ...p1('a'), raisedBy: 'reviewer' }, { ...p1('b'), raisedBy: 'reviewer' }];
  const d = settleDispositions(
    findings,
    [
      { id: 'b', disposition: 'fixed', reason: 'first' },
      { id: 'zzz', disposition: 'fixed', reason: 'invented' },
      { id: 'b', disposition: 'rebutted', reason: 'second' },
    ],
    CTX,
  );
  assert.deepEqual(
    d.dispositions.map((x) => [x.id, x.disposition, x.reason]),
    [
      ['a', 'not-addressed', ''],
      ['b', 'fixed', 'first'],
    ],
  );
  assert.deepEqual(d.dropped, ['zzz']);
  assert.deepEqual(d.duplicates, ['b']);
  assert.equal(
    dispositionSummary(d),
    'fix-1: 1 fixed, 0 rebutted by the fixer, 0 deferred, 1 not addressed, of 2; ' +
      'ignored ids not in the prompt: zzz; duplicate ids, first kept: b',
  );
});

test('seats: every foundBy seat, else the stamp for the round answered, else none', () => {
  const twoFinders: Finding = {
    ...p1('two'),
    raisedBy: 'reviewer',
    foundBy: [
      { seat: 'roles.reviewer', provider: 'codex', model: 'gpt-x', id: 'two' },
      { seat: 'review.finders[0]', provider: 'claude', model: 'default', id: 'two-b' },
    ],
  };
  const plain: Finding = { ...p1('plain'), raisedBy: 'reviewer' };
  const human: Finding = { ...p1('mine'), raisedBy: 'human' };
  const seatsOf = (f: Finding, ctx = CTX): unknown => settleDispositions([f], [], ctx).dispositions[0]?.seats;

  assert.deepEqual(seatsOf(twoFinders), [
    { seat: 'roles.reviewer', provider: 'codex', model: 'gpt-x' },
    { seat: 'review.finders[0]', provider: 'claude', model: 'default' },
  ]);
  assert.deepEqual(seatsOf(plain), [{ seat: 'roles.reviewer', provider: 'codex', model: 'gpt-x' }]);
  // A stamp for another round, or none at all, credits nobody: never today's config.
  assert.equal(seatsOf(plain, { ...CTX, reviewSeat: { ...STAMP, round: 3 } }), null);
  assert.equal(seatsOf(plain, { ...CTX, reviewSeat: undefined }), null);
  assert.equal(seatsOf(human), null);
});

test('the review reproducer verdict and the author ride along; a final-fix observation does not', () => {
  const f: Finding = {
    ...p1('r'),
    reproducerOutcomes: [
      { verdict: 'reproduced', at: 'review', gate: 'g', command: 'c', baseline: null, reason: '' } as never,
      { verdict: 'did-not-reproduce', at: 'final-fix', gate: 'g', command: 'c', baseline: null, reason: '' } as never,
    ],
  };
  const [d] = settleDispositions([f], [], CTX).dispositions;
  assert.equal(d?.reproducer, 'reproduced');
  assert.equal(d?.raisedBy, null, 'a finding with no author records none');
});

// ---- the stored stamp ------------------------------------------------------

test('a stored reviewSeat is read back, and a damaged one is dropped rather than repaired', () => {
  const state = freshRun({ prefix: 'vibe-review-seat-' });
  const read = (reviewSeat: unknown): { seat: unknown; repaired: boolean } => {
    const raw = JSON.parse(JSON.stringify({ ...state, reviewSeat })) as Record<string, unknown>;
    const { state: loaded, repairs } = validateStoredState(raw, state.id, state.dir);
    return { seat: loaded.reviewSeat, repaired: repairs.some((r) => JSON.stringify(r).includes('reviewSeat')) };
  };
  assert.deepEqual(read({ round: 0, provider: 'codex', model: 'default' }), {
    seat: { round: 0, provider: 'codex', model: 'default' },
    repaired: false,
  });
  assert.deepEqual(read(undefined), { seat: undefined, repaired: false });
  for (const bad of [{ round: -1, provider: 'codex', model: 'm' }, { round: 0, provider: '', model: 'm' }, 'codex']) {
    assert.deepEqual(read(bad), { seat: undefined, repaired: true }, JSON.stringify(bad));
  }
});

test('a stored fixInFlight is read back, and a damaged one is dropped so the resume numbers a new round', () => {
  const state = freshRun({ prefix: 'vibe-fix-in-flight-' });
  const read = (fixInFlight: unknown): unknown => {
    const raw = JSON.parse(JSON.stringify({ ...state, fixInFlight })) as Record<string, unknown>;
    return validateStoredState(raw, state.id, state.dir).state.fixInFlight;
  };
  assert.deepEqual(read({ round: 2, final: true }), { round: 2, final: true });
  assert.equal(read(undefined), undefined);
  assert.equal(read({ round: 0, final: false }), undefined);
  assert.equal(read({ round: 1, final: 'yes' }), undefined);
});
